"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const exporter=require("../site/source-audit.js");
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync("site/data.js","utf8"),sandbox);
const records=sandbox.window.ANTHROPIC_LIBRARY;
assert.ok(records.length>=100,"Expected official source catalog");
const selected=records.filter(x=>x.topic===records[0].topic).slice(0,3);
const txt=exporter.exportText(selected);
assert.ok(txt.startsWith("\uFEFF"),"UTF-8 BOM");
assert.match(txt,/2026-11-10（历史快照；非实时验证）/);
assert.match(txt,/人工核验日期（待填）/);
assert.ok(txt.includes(selected[0].url));
assert.equal(txt.split("\n").filter(x=>x.includes("https://")&&x.includes("\t")).length,3);
assert.ok(!txt.includes("已验证有效"));
assert.equal(exporter.clean("a\tb\nc"),"a b c");
assert.throws(()=>exporter.exportText("not rows"),TypeError);
assert.ok(exporter.exportText([]).includes("当前筛选的 0 条"));
console.log("source-audit export: 8 assertions passed");
